// Hilfsfunktion, um basierend auf dem Datum den "Artikel des Tages" zu holen
export function getDailyScienceArticle() {
  const dayOfYear = Math.floor(
    (new Date() - new Date(new Date().getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24
  );
  const index = dayOfYear % WISSENSCHAFT_ARTICLES.length;
  return WISSENSCHAFT_ARTICLES[index];
}
